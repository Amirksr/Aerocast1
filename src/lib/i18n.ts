/** Resolve a dotted key path ("a.b.c") against a dictionary object. */
export function resolvePath(dict: Record<string, any>, path: string): string {
  const value = path
    .split(".")
    .reduce((acc: any, part) => (acc && typeof acc === "object" ? acc[part] : undefined), dict);
  return typeof value === "string" ? value : path;
}
